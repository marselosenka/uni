SET SERVEROUTPUT ON;

CREATE OR REPLACE FUNCTION try_lock_account (
    P_IBAN IN accounts.iban%TYPE
)
RETURN BOOLEAN
AS
    V_IBAN accounts.iban%TYPE;

    E_RESOURCE_BUSY EXCEPTION;
    PRAGMA EXCEPTION_INIT(E_RESOURCE_BUSY, -54);
BEGIN
    SELECT iban
    INTO V_IBAN
    FROM accounts
    WHERE iban = P_IBAN
    FOR UPDATE NOWAIT;

    RETURN TRUE;

EXCEPTION
    WHEN E_RESOURCE_BUSY THEN
        RETURN FALSE;

    WHEN OTHERS THEN
        RAISE;
END;
/

SHOW ERRORS FUNCTION try_lock_account;